import type { Show } from './show.ts'

/** Ответ поиска: одна страница выдачи. Фильтр по жанру и нарезку страниц делает сервер. */
export type ShowsPage = {
  /** Шоу этой страницы, не больше трёх. */
  shows: Show[]
  page: number
  pageCount: number
  /** Сколько шоу стоит перед первым шоу этой страницы: по нему сайт нумерует карточки. */
  offset: number
  /** Сколько шоу осталось после фильтра по жанру. */
  found: number
  /** Сколько шоу в выдаче без фильтра. */
  total: number
  /** Жанр, по которому отфильтрована выдача. null — фильтра нет. */
  genre: string | null
  /** Жанры всей выдачи: сколько шоу в каждом, от частого к редкому. */
  genres: { name: string; count: number }[]
}
